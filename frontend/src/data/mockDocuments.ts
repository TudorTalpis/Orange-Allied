import type {
  Document,
  DocumentActivityEntry,
  ExtractedField,
} from "@/types";

/* ------------------------------------------------------------------ */
/*  Field factories                                                    */
/*  Extraction output is modelled generically so that every document   */
/*  class can expose its own fields through one rendering component.   */
/* ------------------------------------------------------------------ */

type FieldSeed = [
  key: string,
  label: string,
  value: ExtractedField["value"],
  type: ExtractedField["type"],
  confidence: number,
  extra?: Partial<ExtractedField>,
];

function fields(seeds: FieldSeed[]): ExtractedField[] {
  return seeds.map(([key, label, value, type, confidence, extra]) => ({
    key,
    label,
    value,
    type,
    confidence,
    ...extra,
  }));
}

function activity(
  entries: Array<[string, string, DocumentActivityEntry["actorType"], string, string?]>,
): DocumentActivityEntry[] {
  return entries.map(([timestamp, action, actorType, actor, detail], index) => ({
    id: `act_${index}_${timestamp}`,
    timestamp,
    action,
    actorType,
    actor,
    detail,
  }));
}

